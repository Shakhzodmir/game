-- A whole session on the strict Defold stubs (tests/client/session_harness.lua): the real app script, overlay, audio
-- object and every screen script, from the splash to the town and back, in one Lua state. The tests follow the
-- player: splash -> level 1 with its tutorial -> win -> results -> town (rewards, a task) -> start window -> level N ->
-- out of moves (+5 moves for coins / give up) -> defeat -> retry or town -> no lives -> lives window -> refill -> shop ->
-- settings (language under an open window, input mode, reset) -> app focus -> window resize -> save failure.
-- What each screen does alone is tested by its own file; what only a session shows is the traffic between them:
-- the params a screen is opened with, what a screen leaves behind (bus subscriptions, the input stack, the open
-- attempt), the queue of rewards, the fades.

local S = require("tests.client.session_harness")
local bus = require("client.bus")
local link = require("client.level_link")
local rewards = require("client.rewards")
local flow = require("client.flow")
local i18n = require("client.i18n")
local audio = require("client.audio")

local LEVEL = "screens/level/level.gui_script"
local TOWN = "screens/town/town.gui_script"

-- Wins n levels through the meta (no board): stars, coins, chests as in the game.
local function advance(app, n)
	for _ = 1, n do assert(flow.debug_win(3)) end
end

local function on_town(s)
	s:step_until(function() return s.app.screen == "town" and not s.app.transitioning end, 8, "the town")
	s:run(5) -- the rewards a level brought are over
	s:step_until(function() return not s.app.ui.busy end, 40, "the town to be at rest")
end

local function on_level(s, id)
	s:step_until(function()
		return s.app.screen == "level" and not s.app.transitioning and (id == nil or s.app.params.level_id == id)
	end, 10, "the level screen")
	s:run(1)
end

-- the town's Level button -> the start window -> Play
local function start_from_town(s, id)
	s:tap_target("level")
	s:step_until(function() return s.app.ui.popup == "start" end, 3, "the start window")
	s:run(1)
	s:tap_target("play")
	on_level(s, id)
end

local function win_level(s)
	assert_true(link.board.session:qa("win").ok)
	s:step_until(function() return s.app.ui.popup == "result" end, 400, "the results window")
	s:run(1.5)
end

-- plays hint moves until the moves are out
local function run_out_of_moves(s)
	link.board.session:qa("autoplay", { "100" })
	s:step_until(function() local st = link.status(); return st and st.state == "out_of_moves" end, 600, "out of moves")
	s:step_until(function() return s.app.ui.popup == "moves" end, 20, "the moves window")
	s:run(1.2)
	assert_eq(link.board.session.auto, nil, "the autoplay ended at the moves window")
end

local function texts(s, path)
	return table.concat(s:texts(path), " | ")
end

local function expect_text(s, path, text)
	assert_true(s:has_text(path, text), "'" .. text .. "' is not on " .. path .. ": " .. texts(s, path))
end

describe("a session: the first launch", function()
	it("boots into the splash and goes straight into level 1, with the attempt open", function()
		S.run({}, function(s)
			s:wait_screen("splash")
			assert_true(s.app.first_launch())
			assert_eq(#bus.default.subs, 1, "only the overlay listens on the splash")
			s:step_until(function() return s.app.screen == "level" and not s.app.transitioning end, 8, "level 1")
			assert_eq(s.app.params.level_id, 1)
			assert_eq(s.app.params.from, "splash")
			assert_true(s.app.meta:run() ~= nil, "the attempt is open in the meta")
			assert_eq(s.app.meta:run().level_id, 1)
			s:step(30)
			assert_eq(s.app.ui.screen, "level")
			assert_eq(#bus.default.subs, 4, "overlay + board + HUD + effects")
			-- the splash is gone: its scene was freed, the level's scripts are the ones in the input stack
			assert_eq(s.screens.splash, nil)
			assert_true(s.screens.level ~= nil)
		end)
	end)

	it("ignores touches while a screen fades in: the overlay is on top of the screens", function()
		S.run({}, function(s)
			s:step_until(function()
				local lv = s.app.ui and s.app.ui.level
				return s.app.transitioning and lv and lv.targets and s.app.overlay.fading
			end, 8, "the level to be under the fade")
			s:tap_target_at(s.app.ui.level.targets.pause)
			assert_eq(s.app.ui.popup, nil, "a touch under the fade opens nothing")
			s:step_until(function() return not s.app.transitioning end, 4, "the fade to end")
			s:run(1)
			s:tap_target_at(s.app.ui.level.targets.pause)
			s:step_until(function() return s.app.ui.popup == "pause" end, 3, "the pause window once the fade is over")
		end)
	end)

	it("guides the first swap of level 1 with real touches: a wrong swipe is turned away, the guided one goes through", function()
		S.run({}, function(s)
			on_level(s, 1)
			s:step(60)
			local function tut() return s.app.ui.level.tutorial end
			assert_eq(tut().index, 1)
			local moves = link.status().moves_left
			s:swipe_cells({ 1, 1 }, { 2, 1 })
			s:step(30)
			assert_eq(link.status().moves_left, moves, "a swipe the guide does not want costs no move")
			assert_true((tut().blocked or 0) >= 1)
			s:swipe_cells({ 4, 1 }, { 4, 2 }) -- the first step of content/tutorials.json: [3,0] -> [3,1]
			s:step(120)
			assert_eq(link.status().moves_left, moves - 1)
			assert_eq(tut().index, 2, "the next step of the lesson")
			assert_true(s.app.meta:run().moved, "the first move was told to the meta")
		end)
	end)

	it("wins level 1: the results, then the town brings the rewards in, and nothing is left behind", function()
		S.run({ audio = true }, function(s)
			local base = #bus.default.subs -- overlay, audio
			on_level(s, 1)
			win_level(s)
			assert_eq(s.app.meta:level_to_play(), 2)
			assert_eq(rewards.count(), 1, "the win waits in the queue for the town")
			expect_text(s, LEVEL, "Level complete!")
			expect_text(s, LEVEL, "Next level")
			s:tap_target("town")
			s:step_until(function() return s.app.screen == "town" and not s.app.transitioning end, 8, "the town")
			s:run(0.6)
			assert_eq(#bus.default.subs, base + 1, "the level's subscriptions are closed, the town's is open")
			assert_true(s.app.ui.busy, "the rewards play")
			s:step_until(function() return not s.app.ui.busy end, 30, "the rewards to land")
			assert_eq(rewards.count(), 0)
			assert_eq(s.app.ui.disp.coins, s.app.meta:coins(), "the top bar shows what the meta holds")
			assert_eq(s.app.ui.disp.stars, s.app.meta:stars())
			assert_eq(s.app.ui.hold.coins, 0)
			assert_eq(s.app.ui.hold.stars, 0)
			assert_eq(s.app.meta:run(), nil)
		end)
	end)
end)

describe("a session: the town", function()
	it("builds the first task (the stem joins the track) and starts the next level through the start window", function()
		S.run({ audio = true }, function(s)
			on_level(s, 1)
			win_level(s)
			s:tap_target("town")
			on_town(s)
			assert_eq(s.app.ui.hint, "town_first_task")
			local stems = audio.status.stems_on
			s:tap_target("task")
			s:step_until(function() return not s.app.ui.busy end, 30, "the task animation")
			assert_eq(s.app.meta:next_task().id, "lamps")
			assert_eq(s.app.meta:stars(), 0)
			assert_eq(audio.status.stems_on, stems + 1, "the new layer of the track is on")
			start_from_town(s, 2)
			assert_eq(s.app.params.from, "town")
			assert_eq(s.app.params.run.attempt, 1)
			assert_true(s.app.meta:run() ~= nil)
			assert_eq(s.app.ui.level.state, "playing")
		end)
	end)

	it("wins two levels in a row through Next level and Play, and the town then brings both rewards in", function()
		S.run({}, function(s)
			on_level(s, 1)
			win_level(s)
			s:tap_target("next")
			s:step_until(function() return s.app.ui.popup == "start" end, 3, "the start window of level 2")
			s:run(1)
			s:tap_target("play")
			on_level(s, 2)
			assert_eq(s.app.params.from, "level", "Play on the level screen starts the attempt from there")
			assert_eq(rewards.count(), 1, "the first win is still queued: the town was not visited")
			win_level(s)
			assert_eq(rewards.count(), 2)
			local coins, stars = s.app.meta:coins(), s.app.meta:stars()
			s:tap_target("town")
			s:step_until(function() return s.app.screen == "town" and not s.app.transitioning end, 8, "the town")
			s:run(0.6)
			assert_true(s.app.ui.busy)
			assert_true(s.app.ui.disp.coins < coins, "the counters wait for the flights")
			s:step_until(function() return not s.app.ui.busy end, 40, "the rewards to land")
			assert_eq(s.app.ui.disp.coins, coins)
			assert_eq(s.app.ui.disp.stars, stars)
			assert_eq(rewards.count(), 0)
		end)
	end)

	it("completes a district: the concert, the chest and the next district", function()
		S.run({ audio = true, setup = function(app)
			-- everything but the last task of the Café is built
			local d = app.meta:district("cafe")
			local need = 0
			for _, t in ipairs(d.tasks) do need = need + t.cost end
			app.meta:_change("test_stars", { { "stars", need } })
			for i, t in ipairs(d.tasks) do
				if i < #d.tasks then assert(app.meta:complete_task("cafe", t.id)) end
			end
			app.commit("test")
		end }, function(s)
			s.app.show_screen("town", {})
			on_town(s)
			assert_eq(s.app.meta:next_task().id, "sign")
			local coins = s.app.meta:coins()
			s:tap_target("task")
			local seen, tapped = {}, {}
			for _ = 1, 60 * 90 do
				s:frame()
				local ui = s.app.ui
				local key = (ui.step or "") .. "/" .. (ui.popup or "")
				if seen[#seen] ~= key then seen[#seen + 1] = key end
				if ui.popup == "chest" and ui.popup_targets then
					-- the closed chest first (a tap opens it), then the Collect button of the open one; each once
					local name = (ui.popup_targets.collect and "collect") or (ui.popup_targets.chest and "chest") or nil
					if name and not tapped[name] then
						tapped[name] = true
						s:run(1.5) -- the window and the items have come in
						s:tap_target(name)
					end
				end
				if #seen >= 4 and not ui.busy then break end
			end
			assert_false(s.app.ui.busy, "the show is over: " .. table.concat(seen, " > "))
			local joined = table.concat(seen, " ")
			assert_true(string.find(joined, "concert/concert", 1, true), "the concert played: " .. joined)
			assert_true(string.find(joined, "chest/chest", 1, true), "the chest opened: " .. joined)
			assert_eq(s.app.meta:current_district(), "jazz", "the next district is being built")
			assert_eq(s.app.ui.district, "jazz", "and the town shows it")
			assert_true(s.app.meta:coins() > coins, "the chest paid")
			assert_eq(s.app.ui.disp.coins, s.app.meta:coins(), "the top bar caught up")
		end)
	end)
end)

describe("a session: out of moves, defeat, lives", function()
	-- level 60 with five moves: the hint moves cannot finish it
	local function hard(extra)
		local opts = { levels = { [60] = function(d) d.moves = 5 end }, setup = function(app) advance(app, 59) end }
		for k, v in pairs(extra or {}) do opts[k] = v end
		return opts
	end

	it("sells +5 moves for coins, then lets the player give up; the defeat offers a retry in two taps", function()
		S.run(hard({ audio = true }), function(s)
			on_town(s)
			start_from_town(s, 60)
			local coins = s.app.meta:coins()
			run_out_of_moves(s)
			expect_text(s, LEVEL, "Out of moves!")
			expect_text(s, LEVEL, "+5 moves")
			s:tap_target("continue")
			s:run(1.5)
			assert_eq(s.app.ui.popup, nil, "the window closed")
			assert_eq(link.status().state, "playing")
			assert_true(link.status().moves_left >= 4, "the bought moves are on the board")
			assert_eq(s.app.meta:run().continues, 1, "the meta booked the purchase")
			assert_eq(s.app.meta:coins(), coins - 700)
			run_out_of_moves(s)
			s:tap_target("give_up")
			s:step_until(function() return s.app.ui.popup == "defeat" end, 20, "the defeat window")
			s:run(1.5)
			expect_text(s, LEVEL, "Level failed")
			assert_eq(s.app.meta:run(), nil, "the attempt is closed")
			-- retry: the start window of the same level, then Play
			s:tap_target("retry")
			s:step_until(function() return s.app.ui.popup == "start" end, 3, "the start window")
			s:run(1)
			s:tap_target("play")
			on_level(s, 60)
			assert_eq(s.app.params.from, "level")
			assert_eq(s.app.params.run.attempt, 2)
			assert_true(s.app.meta:run() ~= nil)
			-- and out of the second attempt to the town: the loss is shown there
			run_out_of_moves(s)
			s:tap_target("give_up")
			s:step_until(function() return s.app.ui.popup == "defeat" end, 20, "the second defeat")
			s:run(1.5)
			s:tap_target("town")
			on_town(s)
			assert_eq(s.app.meta:run(), nil)
			assert_eq(rewards.count(), 0, "the town showed the loss")
		end)
	end)

	it("sends a player without lives to the lives window, and a refill makes Play work", function()
		S.run({ levels = { [21] = function(d) d.moves = 5 end }, setup = function(app, s)
			advance(app, 20)
			s.E.clock = s.E.clock + 3600 * 3 -- the unlimited lives of the chests are over
		end }, function(s)
			on_town(s)
			assert_eq(s.app.meta:lives(s.app.now()).count, 5)
			for _ = 1, 5 do
				start_from_town(s, 21)
				run_out_of_moves(s)
				s:tap_target("give_up")
				s:step_until(function() return s.app.ui.popup == "defeat" end, 20, "the defeat window")
				s:run(1.5)
				s:tap_target("town")
				on_town(s)
			end
			assert_eq(s.app.meta:lives(s.app.now()).count, 0)
			local coins = s.app.meta:coins()
			s:tap_target("level")
			s:step_until(function() return s.app.ui.popup == "start" end, 3, "the start window")
			s:run(1)
			expect_text(s, TOWN, "You need a life to play")
			s:tap_target("play")
			s:step_until(function() return s.app.ui.popup == "lives" end, 3, "the lives window")
			s:run(1)
			assert_eq(s.app.screen, "town", "Play did not start anything")
			assert_eq(s.app.meta:run(), nil)
			s:tap_target("refill")
			s:step_until(function() return s.app.ui.popup == "start" end, 5, "the start window back on top")
			assert_eq(s.app.meta:lives(s.app.now()).count, 5)
			assert_eq(s.app.meta:coins(), coins - 600)
			s:run(0.5)
			s:tap_target("play")
			on_level(s, 21)
			assert_eq(s.app.params.from, "town")
		end)
	end)

	it("books a loss when the player leaves through the pause window after a move, and nothing before it", function()
		S.run({ setup = function(app, s)
			advance(app, 20)
			s.E.clock = s.E.clock + 3600 * 3 -- the unlimited lives of the chests are over
		end }, function(s)
			on_town(s)
			-- before the first move: the attempt is dropped, no life is lost
			start_from_town(s, 21)
			s:tap_target_at(s.app.ui.level.targets.pause)
			s:step_until(function() return s.app.ui.popup == "pause" end, 3, "the pause window")
			s:run(1)
			s:tap_target("leave")
			on_town(s)
			assert_eq(s.app.meta:run(), nil)
			assert_eq(s.app.meta:lives(s.app.now()).count, 5)
			-- after a move: a loss (the question first, a life and the streak are at stake)
			start_from_town(s, 21)
			link.board.session:qa("hint_move")
			s:run(2)
			assert_true(s.app.meta:run().moved)
			s:tap_target_at(s.app.ui.level.targets.pause)
			s:step_until(function() return s.app.ui.popup == "pause" end, 3, "the pause window")
			s:run(1)
			s:tap_target("leave")
			s:step_until(function() return s.app.ui.popup == "confirm" end, 3, "the question")
			s:run(1)
			s:tap_target("confirm")
			on_town(s)
			assert_eq(s.app.meta:run(), nil)
			assert_eq(s.app.meta:lives(s.app.now()).count, 4, "the loss cost a life")
			assert_eq(rewards.count(), 0, "and the town showed it")
		end)
	end)
end)

describe("a session: the shop, the settings and the app", function()
	it("buys a pack of boosters in the shop for coins", function()
		S.run({ setup = function(app) advance(app, 9) end }, function(s)
			on_town(s)
			local coins, stock = s.app.meta:coins(), s.app.meta:booster_count("stick")
			s:tap_target("nav_shop")
			s:step_until(function() return s.app.ui.popup == "shop" end, 3, "the shop")
			s:run(1)
			s:tap_target("pack_stick")
			s:run(1.5)
			assert_eq(s.app.meta:booster_count("stick"), stock + 3)
			assert_eq(s.app.meta:coins(), coins - 450)
			s:tap_target("close")
			s:step_until(function() return s.app.ui.popup == nil end, 3, "the shop to close")
		end)
	end)

	it("switches the language under an open window in the town and on the level, and keeps it", function()
		S.run({ setup = function(app) advance(app, 2) end }, function(s)
			on_town(s)
			s:tap_target("settings")
			s:step_until(function() return s.app.ui.popup == "settings" end, 3, "the settings")
