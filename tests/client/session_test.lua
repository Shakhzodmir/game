			s:step_until(function() return s.app.ui.popup == "settings" end, 3, "the settings on the level")
			s:run(1)
			s:tap_target("lang_en")
			s:run(1.5)
			assert_eq(i18n.language(), "en")
			expect_text(s, LEVEL, "Settings")
			expect_text(s, LEVEL, "Moves")
			assert_eq(s.app.ui.popups[1], "pause")
			assert_eq(s.app.ui.popups[2], "settings")
			-- the input mode applies to the board that is on display
			s:tap_target("input_taptap")
			s:run(1)
			assert_eq(s.app.meta:settings().input_mode, "taptap")
			assert_eq(link.board.input.mode, "taptap")
		end)
	end)

	it("resets the save from the settings: the splash again, and the first launch is back", function()
		S.run({ setup = function(app) advance(app, 5) end }, function(s)
			on_town(s)
			assert_eq(s.app.meta:level_to_play(), 6)
			s:tap_target("settings")
			s:step_until(function() return s.app.ui.popup == "settings" end, 3, "the settings")
			s:run(1)
			s:tap_target("reset")
			s:step_until(function() return s.app.ui.popup == "confirm" end, 3, "the question")
			s:run(1)
			s:tap_target("confirm")
			s:step_until(function() return s.app.screen == "splash" and not s.app.transitioning end, 8, "the splash")
			assert_eq(s.app.meta:level_to_play(), 1)
			assert_eq(s.app.meta:coins(), 500)
			assert_eq(rewards.count(), 0)
			assert_eq(#bus.default.subs, 1, "the town and its windows left nothing behind")
			s:step_until(function() return s.app.screen == "level" and not s.app.transitioning end, 8, "level 1 again")
			assert_eq(s.app.params.level_id, 1)
		end)
	end)

	it("stands still while the app is away, plays on when it is back, and the music catches up", function()
		S.run({ audio = true }, function(s)
			on_level(s, 1)
			s:step(30)
			local session = link.board.session
			local t0 = session.tick
			s.E.window_listener(nil, window.WINDOW_EVENT_FOCUS_LOST, {})
			s:run(1)
			assert_eq(session.tick, t0, "no ticks while the app is away")
			assert_true(session.hold)
			assert_false(s.app.meta:dirty(), "the save was written when the app went away")
			local resyncs = audio.status.resyncs
			s.E.clock = s.E.clock + 30 -- a long time away
			s.E.window_listener(nil, window.WINDOW_EVENT_FOCUS_GAINED, {})
			s:run(1)
			assert_false(session.hold)
			assert_true(session.tick > t0, "the game goes on")
			assert_true(session.tick < t0 + 180, "and does not play back the time it was away")
			assert_eq(audio.status.resyncs, resyncs + 1, "the stems restart at the clock position")
		end)
	end)

	it("lays the town and the level out again when the window changes", function()
		S.run({ setup = function(app) advance(app, 2) end }, function(s)
			on_town(s)
			for _, size in ipairs({ { 390, 844 }, { 1280, 720 }, { 768, 1024 }, { 720, 1280 } }) do
				s.E.set_window(size[1], size[2])
				s:run(0.5)
				assert_eq(s.app.screen, "town")
			end
			start_from_town(s, 3)
			local rect = link.board_rect()
			for _, size in ipairs({ { 390, 844 }, { 1280, 720 }, { 768, 1024 }, { 720, 1280 } }) do
				s.E.set_window(size[1], size[2])
				s:run(0.5)
				local r = link.board_rect()
				assert_true(r.x1 > r.x0 and r.y1 > r.y0)
