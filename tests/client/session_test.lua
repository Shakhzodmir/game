			expect_text(s, TOWN, "Settings")
			s:tap_target("lang_ru")
			s:run(1.5)
			assert_eq(i18n.language(), "ru")
			assert_eq(s.app.meta:settings().language, "ru")
			expect_text(s, TOWN, "Настройки")
			assert_eq(s.app.ui.popup, "settings", "the window stayed open")
			s:tap_target("close")
			s:run(1)
			start_from_town(s, 3)
			expect_text(s, LEVEL, "Ходы")
			-- the pause window and the settings on top of it, on the level
			s:tap_target_at(s.app.ui.level.targets.pause)
			s:step_until(function() return s.app.ui.popup == "pause" end, 3, "the pause window")
			s:run(1)
			expect_text(s, LEVEL, "Пауза")
