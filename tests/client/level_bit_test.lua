-- client/level_bit.lua: what Bit does for the events of a level.

local level_bit = require("client.level_bit")

local function ops(lb)
	local out = {}
	for _, a in ipairs(lb:take()) do out[#out + 1] = a.op .. (a.mood and (":" .. a.mood) or "") end
	return out
end

describe("client.level_bit", function()
	it("dances on the beat from the start", function()
		local lb = level_bit.new({ bpm = 96, state = "playing", left = 20 })
		local a = lb:take()
		assert_eq(#a, 1)
		assert_eq(a[1].op, "dance")
		assert_eq(a[1].bpm, 96)
		assert_same(lb:take(), {}) -- the queue is emptied
		assert_eq(lb:mood(), "dance")
	end)

	it("is scared on the last moves and relaxes when moves are bought", function()
		local lb = level_bit.new({ state = "playing", left = 20 })
		lb:take()
		lb:event("level_moves", { left = 6 })
		assert_same(ops(lb), {})
		lb:event("level_moves", { left = 5 })
		assert_same(ops(lb), { "stay:worried" })
		lb:event("level_moves", { left = 4 })
		assert_same(ops(lb), {}) -- already scared: no new action
		lb:event("level_state", { state = "out_of_moves" })
		lb:event("level_moves", { left = 10 }) -- "+5 moves" (and more)
		lb:event("level_state", { state = "playing" })
		assert_same(ops(lb), { "dance" })
	end)

	it("scratches on a combo and goes back to dancing", function()
		local lb = level_bit.new({ bpm = 100, state = "playing", left = 20 })
		lb:take()
		lb:event("level_special", { special = "riff" }) -- a single special: no scratch
		assert_same(ops(lb), {})
		lb:event("level_special", { special = "sub", combo = "bass_drop" })
		local a = lb:take()
		assert_eq(a[1].op, "mood")
		assert_eq(a[1].mood, "scratch")
		assert_eq(a[1].seconds, level_bit.SCRATCH)
		lb:update(level_bit.SCRATCH - 0.1)
		assert_same(ops(lb), {})
		lb:update(0.2)
		assert_same(ops(lb), { "dance" })
		-- a second combo during the first starts the scratch over
		lb:event("level_special", { combo = "cross" })
		lb:take()
		lb:update(1)
		lb:event("level_special", { combo = "trio" })
		assert_same(ops(lb), { "mood:scratch" })
	end)

	it("covers his ears when the noise grows, also on the last moves", function()
		local lb = level_bit.new({ state = "playing", left = 12 })
		lb:take()
		lb:event("level_noise", { x = 2, y = 3 })
		local a = lb:take()
		assert_eq(a[1].op, "worry")
		assert_eq(a[1].seconds, level_bit.EARS)
		lb:update(level_bit.EARS + 0.1)
		assert_same(ops(lb), { "dance" })
		-- scared on the last moves: after the ears he is scared again, not dancing
		lb:event("level_moves", { left = 3 })
		lb:take()
		lb:event("level_noise", {})
		lb:take()
		lb:update(level_bit.EARS + 0.1)
		assert_same(ops(lb), { "stay:worried" })
	end)

	it("cheers when a goal is done or a big cascade word shows", function()
		local lb = level_bit.new({ state = "playing", left = 20 })
		lb:take()
		lb:event("level_goal", { index = 1, left = 3 })
		assert_same(ops(lb), {})
		lb:event("level_goal", { index = 1, left = 0 })
		local a = lb:take()
		assert_eq(a[1].op, "cheer")
		assert_eq(a[1].times, 1)
		lb:update(2)
		assert_same(ops(lb), { "dance" })
		lb:event("level_praise", { index = 3 }) -- "Drive!" is not enough
		assert_same(ops(lb), {})
		lb:event("level_praise", { index = 4 })
		assert_same(ops(lb), { "cheer" })
	end)

	it("jumps for joy at the win and stays happy, and is sad at the defeat for good", function()
		local lb = level_bit.new({ state = "playing", left = 2 })
		lb:take()
		lb:event("level_state", { state = "won_wait" })
		assert_same(ops(lb), { "cheer" })
		lb:update(5)
		assert_same(ops(lb), { "dance" }) -- the final concert: a dance
		lb:event("level_state", { state = "concert" })
		lb:event("level_state", { state = "complete" })
		local a = lb:take()
		assert_eq(a[1].op, "cheer")
		assert_true(a[1].seconds > 1e6) -- the happy face stays
		lb:event("level_noise", {}) -- the level is over: nothing changes him
		lb:event("level_state", { state = "playing" })
		assert_same(ops(lb), {})
		local lb2 = level_bit.new({ state = "playing", left = 0 })
		lb2:take()
		lb2:event("level_state", { state = "out_of_moves" })
		lb2:event("level_state", { state = "lost" })
		assert_same(ops(lb2), { "stay:sad" })
		lb2:event("level_special", { combo = "cross" })
		assert_same(ops(lb2), {})
		assert_eq(lb2:mood(), "sad")
	end)

	it("is scared when the moves are gone", function()
		local lb = level_bit.new({ state = "playing", left = 1 })
		assert_eq(lb:take()[1].op, "stay") -- the last move: worried from the start
		lb:event("level_moves", { left = 0 })
		lb:event("level_state", { state = "out_of_moves" })
		assert_same(ops(lb), {})
		assert_eq(lb:mood(), "worried")
	end)

	it("does not dance under reduced motion but shows his moods", function()
		local lb = level_bit.new({ state = "playing", left = 20, reduced = true })
		assert_same(ops(lb), { "idle" })
		lb:event("level_special", { combo = "cross" })
		assert_same(ops(lb), { "mood:scratch" })
		lb:update(5)
		assert_same(ops(lb), { "idle" })
		lb:set_reduced(false)
		assert_same(ops(lb), { "dance" })
		lb:set_reduced(true)
		assert_same(ops(lb), { "idle" })
	end)

	it("takes a new tempo while dancing", function()
		local lb = level_bit.new({ bpm = 100, state = "playing", left = 20 })
		lb:take()
		lb:set_bpm(120)
		local a = lb:take()
		assert_eq(a[1].op, "dance")
		assert_eq(a[1].bpm, 120)
		lb:set_bpm(-4)
		lb:set_bpm(nil)
		assert_same(ops(lb), {})
	end)

	it("tells cheaply whether an action is waiting", function()
		local lb = level_bit.new({ state = "playing", left = 20 })
		assert_true(lb:pending())
		lb:take()
		assert_false(lb:pending())
		lb:event("level_noise", {})
		assert_true(lb:pending())
		assert_eq(#lb:take(), 1)
		assert_false(lb:pending())
	end)

	it("says again what he is doing when the picture is rebuilt, in every state", function()
		local lb = level_bit.new({ bpm = 90, state = "playing", left = 20 })
		lb:take()
		lb:replay()
		local a = lb:take()
		assert_eq(#a, 1)
		assert_eq(a[1].op, "dance")
		assert_eq(a[1].bpm, 90)
		-- scared on the last moves
		lb:event("level_moves", { left = 3 })
		lb:take()
		lb:replay()
		assert_same(ops(lb), { "stay:worried" })
		-- the end of the level: a face that stays
		lb:event("level_state", { state = "lost" })
		lb:take()
		lb:replay()
		assert_same(ops(lb), { "stay:sad" })
		local won = level_bit.new({ state = "playing", left = 9 })
		won:take()
		won:event("level_state", { state = "complete" })
		won:take()
		won:replay()
		local w = won:take()
		assert_eq(#w, 1)
		assert_eq(w[1].op, "cheer") -- the happy face stays for good
		assert_true(w[1].seconds >= 1e9)
		-- a scratch in progress is shown again for what is left of it
		local sc = level_bit.new({ state = "playing", left = 20 })
		sc:take()
		sc:event("level_special", { combo = "cross" })
		sc:take()
		sc:update(1.0)
		sc:replay()
		local b = sc:take()
		assert_eq(b[1].op, "mood")
		assert_eq(b[1].mood, "scratch")
		assert_true(b[1].seconds > 0 and b[1].seconds <= level_bit.SCRATCH - 0.9)
	end)
end)
