#!/usr/bin/env python3
"""Writes tests/client/font_advances.lua: for every font of assets/gen/fonts/*.font its pixel size,
the characters baked into it and the advance width of each of them (Pillow / FreeType at that size).

    python3 tests/client/font_advances.py

The strict GUI stub of the meta screens (tests/client/town_defold_stub.lua) answers
resource.get_text_metrics with these widths, so the fit-to-width of client/ui.lua shrinks text the
way the engine's metrics would, and it reports glyphs a font does not contain (the engine draws
nothing for them). Re-run after the fonts or the generated .font files change. Needs Pillow.
"""
import os
import re
import sys

from PIL import ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
FONTS = os.path.join(ROOT, 'assets', 'gen', 'fonts')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'font_advances.lua')


def decode_proto_string(raw):
    """Defold text proto string literal body -> str (octal escapes are UTF-8 bytes)."""
    out = bytearray()
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == '\\':
            n = raw[i + 1]
            if n in '01234567':
                j = i + 1
                digits = ''
                while j < len(raw) and len(digits) < 3 and raw[j] in '01234567':
                    digits += raw[j]
                    j += 1
                out.append(int(digits, 8))
                i = j
                continue
            out.extend({'n': b'\n', 't': b'\t', 'r': b'\r'}.get(n, n.encode()))
            i += 2
            continue
        out.extend(c.encode('utf-8'))
        i += 1
    return out.decode('utf-8')


def parse_font(path):
    text = open(path, encoding='utf-8').read()
    ttf = re.search(r'^font:\s*"([^"]+)"', text, re.M).group(1)
    size = int(re.search(r'^size:\s*(\d+)', text, re.M).group(1))
    raw = re.search(r'^characters:\s*"(.*)"\s*$', text, re.M).group(1)
    return ttf, size, decode_proto_string(raw)


def main():
    lines = ['-- Generated by tests/client/font_advances.py - do not edit, re-run the script.',
             '-- Pixel size, baked characters and advance widths (px at that size) of the generated fonts.',
             'return {']
    for name in sorted(os.listdir(FONTS)):
        if not name.endswith('.font'):
            continue
        ttf, size, chars = parse_font(os.path.join(FONTS, name))
        font = ImageFont.truetype(os.path.join(ROOT, ttf.lstrip('/')), size)
        cps = sorted(set(ord(c) for c in chars))
        adv = ', '.join('[%d] = %.3f' % (cp, font.getlength(chr(cp))) for cp in cps)
        lines.append('\t%s = { size = %d, ttf = "%s", advances = { %s } },' % (name[:-5], size, ttf, adv))
    lines.append('}')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    sys.exit(main())
