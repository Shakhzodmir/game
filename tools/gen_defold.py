NOTE_RE = re.compile(r"^([a-z]+)_(\d+)$")
STEM_TOLERANCE = 0.001  # seconds
# The parts of the manifest's mixer contract the engine reads.
MIXER_KEYS = ("notes_same_tick", "group_gain_db", "music_in_level_db", "music_big_combo_db")


def ogg_duration(path):
    """(seconds, sample_rate) of an Ogg Vorbis file from its headers, or None."""
    try:
        with open(path, "rb") as f:
            data = f.read()
    except OSError:
        return None
    i = data.find(b"OggS")
    if i < 0 or len(data) < i + 28:
        return None
    body = i + 27 + data[i + 26]
    packet = data[body:body + 16]
    if packet[:7] != b"\x01vorbis" or len(packet) < 16:
        return None
    rate = struct.unpack("<I", packet[12:16])[0]
    j = data.rfind(b"OggS")
    if rate <= 0 or j < 0 or len(data) < j + 14:
        return None
    granule = struct.unpack("<q", data[j + 6:j + 14])[0]
    if granule <= 0:
        return None
    return granule / rate, rate


def sounds_manifest(warnings):
    m = load_json(rel(SOUNDS, "manifest.json"))
    if not isinstance(m, dict):
        warnings.append("sounds manifest missing: no effect keys (tonal effects play in C), default mixer contract")
        return {}, {}
    keys = {}
    for e in m.get("sfx", []) if isinstance(m.get("sfx"), list) else []:
        if isinstance(e, dict) and isinstance(e.get("name"), str):
            k = e.get("key")
            if isinstance(k, str) and k:
                keys[e["name"]] = k
    src = m.get("mixer") if isinstance(m.get("mixer"), dict) else {}
    mixer = {k: src[k] for k in MIXER_KEYS if k in src}
    if isinstance(mixer.get("notes_same_tick"), dict):  # numbers only, not the prose
        mixer["notes_same_tick"] = {k: v for k, v in mixer["notes_same_tick"].items() if k != "rule"}
    return keys, mixer


def plan_sounds(warnings, errors):
    notes, sfx, music, loops = {}, {}, {}, {}
    comps = []  # (id, path, looping, group)
    for p in list_files(SOUNDS + "/notes", ".ogg"):
        name = os.path.basename(p)[:-4]
        m = NOTE_RE.match(name)
        if not m:
            continue
        if ogg_duration(rel(p)) is None:
            warnings.append("skip (not an Ogg Vorbis file): " + p)
            continue
        cid = "note_" + ident(name)
        notes.setdefault(m.group(1), {})[int(m.group(2))] = cid
        comps.append((cid, p, 0, "notes"))
    for p in list_files(SOUNDS + "/sfx", ".ogg"):
        name = os.path.basename(p)[:-4]
        if ogg_duration(rel(p)) is None:
            warnings.append("skip (not an Ogg Vorbis file): " + p)
            continue
        cid = "sfx_" + ident(name)
        sfx[name] = cid
        comps.append((cid, p, 0, "sfx"))
    lengths = {}
    for p in list_files(MUSIC, ".ogg"):
        parts = p[len(MUSIC) + 1:-4].split("/")
        if len(parts) != 2:
            continue
        did, stem = parts
        cid = "music_" + ident(did) + "_" + ident(stem)
        info = ogg_duration(rel(p))
        if info is None:
            warnings.append("skip (not an Ogg Vorbis file): " + p)
            continue
        music.setdefault(did, {})[stem] = cid
        lengths.setdefault(did, {})[stem] = info[0]
        comps.append((cid, p, 1, "music"))
    for did, stems in sorted(lengths.items()):
        lo, hi = min(stems.values()), max(stems.values())
        loops[did] = round(max(stems.values()), 6)
        if hi - lo > STEM_TOLERANCE:
            detail = ", ".join("%s %.4f s" % (k, v) for k, v in sorted(stems.items()))
            errors.append("stems of %s differ in length by %.1f ms (they would drift apart): %s" % (
                did, (hi - lo) * 1000, detail))
    comps.sort()
    sfx_keys, mixer = sounds_manifest(warnings)
    sfx_keys = {k: v for k, v in sfx_keys.items() if k in sfx}
    return {"notes": notes, "sfx": sfx, "music": music, "loops": loops, "sfx_keys": sfx_keys, "mixer": mixer}, comps


def audio_go_text(comps):
    lines = [
        HEADER_PB.rstrip("\n"),
        "components {",
        '  id: "audio"',
        "  component: " + pb_string(AUDIO_SCRIPT),
        "}",
    ]
    for cid, path, looping, group in comps:
        data = ("sound: %s\nlooping: %d\ngroup: %s\ngain: 1.0\npan: 0.0\nspeed: 1.0\nloopcount: 0\n"
                % (pb_string(res_path(path)), looping, pb_string(group)))
        lines += [
            "embedded_components {",
            "  id: " + pb_string(cid),
            '  type: "sound"',
            "  data: " + pb_string(data),
            "}",
        ]
    return "\n".join(lines) + "\n"


