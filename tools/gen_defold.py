def content_chars():
    """Non-ASCII characters used by the UI strings and the content names."""
    chars = set()
    for p in (rel("client", "i18n.lua"), rel("content", "districts.json")):
        try:
            with open(p, encoding="utf-8") as f:
                chars |= {c for c in f.read() if ord(c) >= 0x80}
        except OSError:
            pass
    return "".join(sorted(chars))


def font_cmap(ttf):
    try:
        from fontTools.ttLib import TTFont  # optional: filters glyphs the font lacks
    except ImportError:
        return None
    try:
        return set(TTFont(ttf).getBestCmap().keys())
    except Exception:  # noqa: BLE001 - a broken font should not stop the generator
        return None


def font_text(name, spec, chars, font_path):
    ttf, size, outline, shadow_a, shadow_blur, shadow_y = spec
    lines = [
        HEADER_PB.rstrip("\n"),
        "font: " + pb_string(font_path),
        'material: "/builtins/fonts/font-df.material"',
        "size: %d" % size,
        "antialias: 1",
        "alpha: 1.0",
        "outline_alpha: %.1f" % (1.0 if outline > 0 else 0.0),
        "outline_width: %.1f" % outline,
        "shadow_alpha: %.2f" % shadow_a,
        "shadow_blur: %d" % shadow_blur,
        "shadow_x: 0.0",
        "shadow_y: %.1f" % shadow_y,
        "output_format: TYPE_DISTANCE_FIELD",
        "all_chars: false",
        "cache_width: 0",
        "cache_height: 0",
        "render_mode: %s" % ("MODE_MULTI_LAYER" if (outline > 0 or shadow_a > 0) else "MODE_SINGLE_LAYER"),
        "characters: " + pb_string(chars),
    ]
    return "\n".join(lines) + "\n"


def resolve_ttf(ttf, warnings):
    """Resource path and local path of the TTF for a font spec, with fallbacks."""
    def usable(name):
        p = rel(FONTS, name)
        return os.path.isfile(p) and os.path.getsize(p) > 0
    if usable(ttf):
        return res_path(FONTS + "/" + ttf), rel(FONTS, ttf)
    others = [f for f in FONT_FALLBACK if usable(f)]
    others += [os.path.basename(p) for p in list_files(FONTS, ".ttf") if usable(os.path.basename(p))]
    if others:
        warnings.append("font %s missing: using %s" % (ttf, others[0]))
        return res_path(FONTS + "/" + others[0]), rel(FONTS, others[0])
    warnings.append("font %s missing and no TTF in %s: using the builtin font (no Cyrillic)" % (ttf, FONTS))
    return BUILTIN_FONT, None


def plan_fonts(warnings):
    """Every font name of FONT_SPECS, always (gui.set_font must never fail)."""
    wanted = BASE_CHARS + CYRILLIC + LATIN1 + EXTRA_CHARS + content_chars()
    out = {}
    for name, spec in sorted(FONT_SPECS.items()):
        font_path, local = resolve_ttf(spec[0], warnings)
        cmap = font_cmap(local) if local else None
        chars = sorted(set(wanted))
        if cmap is not None:
            chars = [c for c in chars if ord(c) in cmap or c == " "]
        out[name] = (spec, "".join(chars), font_path)
    return out


