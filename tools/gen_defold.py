def build_outputs(warnings, errors):
    outputs = {}  # repo-relative path -> bytes
    images = collect_images(warnings)
    dids = district_ids()
    check_loose(images, dids, warnings)
    check_custom_resources(warnings)
    atlases = plan_atlases(images)
    anims = plan_anim_ids(atlases, warnings)
    outputs[GEN + "/placeholder.png"] = white_png()
    for name, keys in atlases.items():
        outputs[GEN + "/" + name + ".atlas"] = atlas_text(keys, images, anims).encode("utf-8")
    fonts = plan_fonts(warnings)
    for name, (spec, chars, font_path) in fonts.items():
        outputs[GEN + "/fonts/" + name + ".font"] = font_text(name, spec, chars, font_path).encode("utf-8")
    sounds, comps = plan_sounds(warnings, errors)
    outputs[GEN + "/audio.go"] = audio_go_text(comps).encode("utf-8")
    guis = {}
    for path, spec in sorted(GUI_SPECS.items()):
        script, groups, mats = spec[:3]
        max_nodes = spec[3] if len(spec) > 3 else GUI_MAX_NODES
        tex = gui_textures(groups, atlases)
        mat = gui_materials(mats)
        guis[path] = (tex, mat)
        outputs[path] = gui_text(script, tex, sorted(fonts), mat, max_nodes).encode("utf-8")
    outputs[INDEX] = index_text(images, atlases, anims, fonts, sounds, guis).encode("utf-8")
    stats = {"images": len(images), "atlases": len(atlases), "fonts": len(fonts), "sounds": len(comps),
             "loose": sum(1 for k in images if is_loose(k))}
    return outputs, stats


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if outputs are out of date or assets are inconsistent")
    args = ap.parse_args()
    warnings, errors = [], []
    outputs, stats = build_outputs(warnings, errors)
    changed = []
    for path, data in sorted(outputs.items()):
        full = rel(path)
        try:
            with open(full, "rb") as f:
                if f.read() == data:
                    continue
        except OSError:
            pass
        changed.append(path)
        if not args.check:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "wb") as f:
                f.write(data)
    # the generator owns assets/gen: remove outputs that are no longer produced
    stale = []
    gen_root = rel(GEN)
    if os.path.isdir(gen_root):
        for dp, _, fns in os.walk(gen_root):
            for fn in fns:
                p = os.path.relpath(os.path.join(dp, fn), ROOT).replace(os.sep, "/")
                if p not in outputs:
                    stale.append(p)
                    if not args.check:
                        os.remove(os.path.join(dp, fn))
    print("gen_defold: %(images)d images (%(loose)d loose), %(atlases)d atlases, %(fonts)d fonts, "
          "%(sounds)d sound components" % stats)
    for w in warnings:
        print("warning: " + w, file=sys.stderr)
    for p in changed:
        print(("out of date: " if args.check else "wrote ") + p)
    for p in sorted(stale):
        print(("stale: " if args.check else "removed ") + p)
    allow = os.environ.get("GLOW_ALLOW_STEM_MISMATCH") == "1"
    for e in errors:
        print(("warning: " if allow else "ERROR: ") + e, file=sys.stderr)
    if errors and not allow:
        print("gen_defold: fix the assets (or set GLOW_ALLOW_STEM_MISMATCH=1 to build anyway)", file=sys.stderr)
        sys.exit(1)
    if args.check and (changed or stale):
        sys.exit(1)


if __name__ == "__main__":
    main()
