def district_ids():
    data = load_json(rel("content", "districts.json")) or {}
    return [d["id"] for d in data.get("districts", []) if isinstance(d, dict) and "id" in d]


def default_slice9(key):
    for pattern, borders in NINE_SLICE_DEFAULTS:
        if fnmatch.fnmatchcase(key, pattern):
            return list(borders)
    return None


def valid_slice9(ns, w, h):
    """Borders fit the image: left + right < w and top + bottom < h."""
    return ns[0] + ns[2] < w and ns[1] + ns[3] < h


def collect_images(warnings):
    """{image_key: {path, w, h, slice9?}} for every png under assets/images."""
    manifest = load_json(rel(IMAGES, "manifest.json"))
    if not isinstance(manifest, dict):
        warnings.append("images manifest missing: built-in nine-slice defaults used")
        manifest = {}
    mfiles = manifest.get("files", {})
    if not isinstance(mfiles, dict):
        mfiles = {}
    images = {}
    for p in list_files(IMAGES, ".png"):
        key = p[len(IMAGES) + 1:-4]
        size = png_size(rel(p))
        if not size or size[0] <= 0 or size[1] <= 0:
            warnings.append("skip (not a png): " + p)
            continue
        e = {"path": p, "w": size[0], "h": size[1]}
        m = mfiles.get(key + ".png")
        ns = m.get("nine_slice") if isinstance(m, dict) else None
        from_manifest = True
        if isinstance(ns, (int, float)) and not isinstance(ns, bool):
            ns = [ns, ns, ns, ns]
        elif not (isinstance(ns, list) and len(ns) == 4 and all(isinstance(v, (int, float)) for v in ns)):
            ns, from_manifest = default_slice9(key), False
        if ns is not None:
            if valid_slice9(ns, size[0], size[1]):
                e["slice9"] = list(ns)  # left, top, right, bottom
            elif from_manifest:
                warnings.append("nine-slice %s does not fit %s (%dx%d): dropped" % (ns, key, size[0], size[1]))
        images[key] = e
    return images


def is_loose(key):
    return key.split("/")[0] in LOOSE_GROUPS and "/" in key


def atlas_for(key):
    """Atlas name for an image key like 'pieces/red', None for a loose image."""
    parts = key.split("/")
    top = parts[0]
    if len(parts) == 1:
        return "misc"
    if is_loose(key):
        return None
    if top in GAME_GROUPS:
        return "game"
    if top in UI_GROUPS:
        return "ui"
    return ident(top)


def meta_keys(images):
    """Image keys of the curated meta atlas (only images of the game atlas)."""
    return sorted(k for k in images if atlas_for(k) == "game"
                  and any(fnmatch.fnmatchcase(k, p) for p in META_ATLAS))


def plan_atlases(images):
    atlases = {"game": [], "ui": []}
    for key in sorted(images):
        a = atlas_for(key)
        if a is not None:
            atlases.setdefault(a, []).append(key)
    extra = meta_keys(images)
    if extra:
        atlases["meta"] = extra
    return {k: sorted(v) for k, v in sorted(atlases.items())}


def plan_anim_ids(atlases, warnings):
    """{image_key: anim id}, unique within each atlas ("white" is reserved).
    Copies in the meta atlas keep the id of their primary atlas."""
    out = {}
    for name, keys in atlases.items():
        if name == "meta":
            continue
        used = {"white"}
        for key in keys:
            base = key.replace("/", "_")
            aid, n = base, 1
            while aid in used:
                n += 1
                aid = "%s_%d" % (base, n)
            if aid != base:
                warnings.append("animation id clash in atlas %s: %s -> %s" % (name, key, aid))
            used.add(aid)
            out[key] = aid
    return out


def check_loose(images, dids, warnings):
    for key, e in sorted(images.items()):
        if not is_loose(key):
            continue
        parts = key.split("/")
        if parts[0] == "districts" and parts[1] not in dids:
            warnings.append("image of a district that is not in content/districts.json: " + key)
        name = parts[-1]
        if (parts[0] == "backgrounds" or name.startswith("bg")) and (e["w"] < MIN_BG[0] or e["h"] < MIN_BG[1]):
            warnings.append("low-res background %s (%dx%d): drawn at up to %.1fx on a 3x phone, ask for %dx%d" % (
                key, e["w"], e["h"], 1170 * 1280 / 720 / e["h"], MIN_BG[0], MIN_BG[1]))


def check_custom_resources(warnings):
    try:
        with open(rel("game.project"), encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return
    m = re.search(r"^custom_resources\s*=\s*(.*)$", text, re.M)
    have = {x.strip().rstrip("/") for x in (m.group(1).split(",") if m else [])}
    for d in LOOSE_DIRS:
        if d not in have:
            warnings.append("game.project custom_resources lacks %s: its loose images will not load" % d)


def atlas_text(keys, images, anims):
    lines = [HEADER_PB.rstrip("\n")]
    entries = [("white", res_path(GEN + "/placeholder.png"))]
    entries += [(anims[k], res_path(images[k]["path"])) for k in keys]
    for aid, path in entries:
        lines += [
            "animations {",
            "  id: " + pb_string(aid),
            "  images {",
            "    image: " + pb_string(path),
            "  }",
            "  playback: PLAYBACK_NONE",
            "}",
        ]
    lines += ["margin: 2", "extrude_borders: 2", "inner_padding: 0"]
    return "\n".join(lines) + "\n"


