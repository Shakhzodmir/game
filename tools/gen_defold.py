#!/usr/bin/env python3
"""Generate the Defold resources that mirror the generated assets.

    python3 tools/gen_defold.py            # from anywhere; paths are repo-relative
    python3 tools/gen_defold.py --check    # exit 1 if any output would change

Reads whatever exists (manifests may be missing or partial; directories are
scanned as the source of truth, manifests only add metadata):
  assets/images/**.png          + assets/images/manifest.json (optional: nine-slice;
                                built-in defaults cover the known panels/buttons)
  assets/sounds/{notes,sfx}/*.ogg + assets/sounds/manifest.json (optional: the
                                key of each effect, the mixer contract)
  assets/music/<district>/<stem>.ogg   (Ogg headers: every stem of a district
                                must have the same length -> error otherwise)
  assets/fonts/*.ttf            (a missing TTF falls back to another one, so
                                every font name always exists)
  content/districts.json        (district ids)
  client/i18n.lua, content/districts.json   (extra glyphs the fonts must contain)

Writes (never edit these by hand, re-run the generator instead):
  assets/gen/*.atlas            game, ui, bit, logo, ... (see grouping)
  assets/gen/placeholder.png    8x8 white image present in every atlas ("white")
  assets/gen/fonts/*.font       title, button, number, body, small
  assets/gen/audio.go           audio game object: main/audio.script + one sound
                                component per note (group "notes"), sfx (group
                                "sfx") and music stem (group "music")
  main/overlay.gui, screens/*/*.gui   minimal GUI scenes (script, fonts,
                                textures, materials); their nodes are built in Lua
  client/assets_index.lua       registry of everything above for the scripts

Atlas grouping:
  game  = pieces + specials + blockers + board + fx      (level)
  ui    = ui (incl. ui/icons)                            (every screen)
  meta  = a curated copy of the game images the meta screens show (goal
          icons, pre-level boosters, a few white fx sprites); only the town
          GUI loads it, so the town never holds the 8 MB game atlas. The
          registry marks these images with also = {"meta"}.
  any other folder = an atlas named after the folder
Loose images (not in any atlas): districts/**, backgrounds/**, bit/** (the
mascot) and logo/**. They ship as custom resources (game.project) and
screens load only the ones on display with image.load + gui.new_texture, so
the town holds one district's pictures instead of all of them, and a big
picture used on one screen does not keep a whole atlas page in memory.
Animation id of an image = its path under assets/images without ".png",
"/" replaced by "_" (pieces/red.png -> "pieces_red"); two images that map to
the same id get "_2", "_3", ... Output is sorted, so re-running on the same
inputs gives byte-identical files.
"""
