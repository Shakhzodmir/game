def lua_value(v, indent=""):
    """Plain JSON-like value -> Lua literal (sorted keys, deterministic)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return "%.10g" % v if isinstance(v, float) else "%d" % v
    if isinstance(v, str):
        return lua_string(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua_value(x) for x in v) + " }" if v else "{}"
    if isinstance(v, dict):
        items = []
        for k in sorted(v):
            key = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else "[" + lua_string(k) + "]"
            items.append("%s = %s" % (key, lua_value(v[k])))
        return "{ " + ", ".join(items) + " }"
    return "nil"


def index_text(images, atlases, anims, fonts, sounds, guis):
    also = set(atlases.get("meta", []))
    L = ["-- Generated by tools/gen_defold.py - do not edit, re-run the generator.",
         "-- Registry of the Defold resources built from assets/: scripts look",
         "-- things up here (usually through client/assets.lua) instead of",
         "-- hard-coding names, so a missing image or sound is a nil, not a crash.",
         "return {"]
    L.append("\tatlases = {")
    for name, keys in atlases.items():
        L.append("\t\t%s = { path = %s, anims = { %s } }," % (
            ident(name), lua_string(res_path(GEN + "/" + name + ".atlas")),
            ", ".join(lua_string(a) for a in ["white"] + [anims[k] for k in keys])))
    L.append("\t},")
    L.append("\t-- atlas images {atlas, anim, w, h, slice9?, also? = {atlases holding a copy}};")
    L.append("\t-- loose images {file, w, h}")
    L.append("\timages = {")
    for key in sorted(images):
        e = images[key]
        extra = (", slice9 = { %s }" % ", ".join("%g" % v for v in e["slice9"])) if "slice9" in e else ""
        a = atlas_for(key)
        if a is None:
            L.append("\t\t[%s] = { file = %s, w = %d, h = %d%s }," % (
                lua_string(key), lua_string(res_path(e["path"])), e["w"], e["h"], extra))
        else:
            if key in also:
                extra += ', also = { "meta" }'
            L.append("\t\t[%s] = { atlas = %s, anim = %s, w = %d, h = %d%s }," % (
                lua_string(key), lua_string(a), lua_string(anims[key]), e["w"], e["h"], extra))
    L.append("\t},")
    L.append("\tfonts = {")
    for name in sorted(fonts):
        spec, _, font_path = fonts[name]
        L.append("\t\t%s = { path = %s, size = %d, ttf = %s }," % (
            name, lua_string(res_path(GEN + "/fonts/" + name + ".font")), spec[1], lua_string(font_path)))
    L.append("\t},")
    L.append("\tsounds = {")
    L.append("\t\tnotes = {")
    for color in sorted(sounds["notes"]):
        items = sounds["notes"][color]
        L.append("\t\t\t%s = { %s }," % (ident(color), ", ".join(
            "[%d] = %s" % (n, lua_string(items[n])) for n in sorted(items))))
    L.append("\t\t},")
    L.append("\t\tsfx = {")
    for name in sorted(sounds["sfx"]):
        L.append("\t\t\t[%s] = %s," % (lua_string(name), lua_string(sounds["sfx"][name])))
    L.append("\t\t},")
    L.append("\t\t-- key of each tonal effect (manifest): transposed to the district key like the notes")
    L.append("\t\tsfx_keys = %s," % lua_value(sounds["sfx_keys"]))
    L.append("\t\tmusic = {")
    for did in sorted(sounds["music"]):
        stems = sounds["music"][did]
        L.append("\t\t\t[%s] = { %s }," % (lua_string(did), ", ".join(
            "[%s] = %s" % (lua_string(s), lua_string(stems[s])) for s in sorted(stems))))
    L.append("\t\t},")
    L.append("\t\t-- loop length of each district track in seconds (from the Ogg headers)")
    L.append("\t\tloops = %s," % lua_value(sounds["loops"]))
    L.append("\t\t-- mixer contract of the audio agent (assets/sounds/manifest.json -> mixer)")
    L.append("\t\tmixer = %s," % lua_value(sounds["mixer"]))
    L.append("\t},")
    L.append("\tguis = {")
    for path in sorted(guis):
        tex, mats = guis[path]
        L.append("\t\t[%s] = { textures = %s, materials = %s }," % (
            lua_string(res_path(path)), lua_value(tex), lua_value(mats)))
    L.append("\t},")
    L.append("}")
    return "\n".join(L) + "\n"


