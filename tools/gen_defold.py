def gui_textures(groups, atlases):
    return [g for g in groups if g in atlases]


def gui_materials(names):
    return [n for n in names if n in MATERIALS and os.path.isfile(rel(MATERIALS[n]))]


def gui_text(script, textures, fonts, materials, max_nodes=GUI_MAX_NODES):
    lines = [HEADER_PB.rstrip("\n"), "script: " + pb_string(script)]
    for f in fonts:
        lines += ["fonts {", "  name: " + pb_string(f), "  font: " + pb_string(res_path(GEN + "/fonts/" + f + ".font")), "}"]
    for t in textures:
        lines += ["textures {", "  name: " + pb_string(t), "  texture: " + pb_string(res_path(GEN + "/" + t + ".atlas")), "}"]
    for m in materials:
        lines += ["materials {", "  name: " + pb_string(m), "  material: " + pb_string(res_path(MATERIALS[m])), "}"]
    lines += [
        'material: "/builtins/materials/gui.material"',
        "adjust_reference: ADJUST_REFERENCE_DISABLED",
        "max_nodes: %d" % max_nodes,
    ]
    return "\n".join(lines) + "\n"


